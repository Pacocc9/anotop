            "def fila_brecha(nombre: str, hombres: float, mujeres: float, periodo: int, fuente: str) -> dict:\n",
            "    brechas = brecha_oficial(hombres, mujeres)\n",
            "    return {\n",
            "        \"indicador\": nombre,\n",
            "        \"hombres_eur\": hombres,\n",
            "        \"mujeres_eur\": mujeres,\n",
            "        \"diferencia_eur\": round(hombres - mujeres, 2),\n",
