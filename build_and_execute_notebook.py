            "    \"\"\"Calcula la brecha según las dos definiciones oficiales exigidas en las bases.\"\"\"\n",
            "    return {\n",
            "        \"brecha_sobre_hombres_pct\": round(((hombres - mujeres) / hombres) * 100, 2),\n",
            "        \"brecha_hombres_sobre_mujeres_pct\": round(((hombres - mujeres) / mujeres) * 100, 2)\n",
            "    }\n",
            "\n",
            "def valor_positivo(fila: pd.Series, columna: str) -> float:\n",
            "    \"\"\"Conversión segura y positiva a valor numérico flotante.\"\"\"\n",
            "    return abs(float(fila[columna]))\n",
