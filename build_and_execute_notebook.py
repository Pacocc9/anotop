            "        \"brecha_hombres_sobre_mujeres_pct\": brechas[\"brecha_hombres_sobre_mujeres_pct\"],\n",
            "        \"periodo\": periodo,\n",
            "        \"territorio\": \"Andalucía\",\n",
            "        \"fuente\": fuente\n",
            "    }\n",
